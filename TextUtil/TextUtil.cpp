#include "TextUtil.h"
#include <cstring>
#include <stdexcept>

#pragma warning (disable:4996)

char* copyDynamic(const char* str)
{
	if (!str || strlen(str) == 0)
		throw std::invalid_argument("Invalid string!");

	size_t len = strlen(str);
	char* temp = new char[len + 1] {};
	strcpy(temp, str);
	return temp;
}

void appendText(char* buffer, int bufferSize, const char* text) {
    size_t currentLength = strlen(buffer);
    size_t textLength = strlen(text);
    if (currentLength + textLength >= bufferSize) return;
    strcpy(buffer + currentLength, text);
}

void makeIndexedName(char* buffer, int bufferSize, const char* prefix, const char* role, int index) {
    if (bufferSize <= 0) return;
    buffer[0] = '\0';
    appendText(buffer, bufferSize, prefix);
    appendText(buffer, bufferSize, "_");
    appendText(buffer, bufferSize, role);

    /* The numbering logic from lines 33 to 50 was generated by an AI agent (ChatGPT). */
    char digits[16];
    int count = 0;
    int value = index;
    if (value == 0) {
        digits[count++] = '0';
    }
    else {
        char reversed[16];
        int reversedCount = 0;
        while (value > 0 && reversedCount < 15) {
            reversed[reversedCount++] = (char)('0' + value % 10);
            value /= 10;
        }
        for (int i = reversedCount - 1; i >= 0; i--) {
            digits[count++] = reversed[i];
        }
    }
    digits[count] = '\0';
    appendText(buffer, bufferSize, digits);
}